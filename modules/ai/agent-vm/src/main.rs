const PROMPT_MAX_BYTES: u64 = 8 * 1024 * 1024;
const META_MAX_BYTES: u64 = 4096;
const CREDENTIAL_MAX_BYTES: u64 = 1024 * 1024;
const HINT_MAX_BYTES: u64 = 1024 * 1024;
const USAGE_MAX_BYTES: u64 = 64 * 1024 * 1024;
const USAGE_MAX_FILES: usize = 4096;
const USAGE_MAX_DEPTH: usize = 64;
const COMMAND_OUTPUT_MAX_BYTES: usize = 8 * 1024 * 1024;

