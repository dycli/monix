    fn publication_order_is_lock_then_trusted_then_exit_code() {
        let steps = final_steps(true, true, true);
        let position = |step: FinalStep| {
            steps
                .iter()
                .position(|candidate| *candidate == step)
                .expect("step present")
        };
        assert_eq!(steps.last(), Some(&FinalStep::PublishExitCode));
        assert!(position(FinalStep::CapturePatch) < position(FinalStep::LockExchange));
        assert!(position(FinalStep::LockExchange) < position(FinalStep::KillExecutor));
        assert!(position(FinalStep::KillExecutor) < position(FinalStep::ResetTrusted));
        assert!(position(FinalStep::ResetTrusted) < position(FinalStep::PublishUsage));
    }

