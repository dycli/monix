// Guest task supervisor, running as guest root inside a disposable
// microVM. Waits for the host drainer to deliver a task into the virtiofs
// exchange, validates the host-staged metadata and the single staged
// credential, prepares the context capsule as the selected unprivileged
// executor, runs it, captures the workspace patch, distills a usage record
// and publishes the exit code last.
//
// Guest root is the orchestration authority; executors run as unprivileged
// users. Everything on the task share and in the capsule is treated as
// hostile: no symlink following, bounded reads, no shell interpolation.
// Fixed external tools do the extraction and execution; every
// orchestration, validation and publication decision lives here.

use std::collections::BTreeMap;
use std::fs::{self, File, OpenOptions};
use std::io::{Read, Write};
use std::os::unix::fs::{MetadataExt, OpenOptionsExt, PermissionsExt};
